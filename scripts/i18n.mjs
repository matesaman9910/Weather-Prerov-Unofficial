export function normalizeLanguage(value) {
  const normalized = String(value || "").toLowerCase().split("-")[0];
  return SUPPORTED_LANGUAGES.includes(normalized) ? normalized : null;
}

export function resolveLanguage(savedLanguage, navigatorLanguage) {
  return normalizeLanguage(savedLanguage) || normalizeLanguage(navigatorLanguage) || "en";
}

export function createTranslator(language) {
  const selected = messages[normalizeLanguage(language) || "en"];
  return (key, values = {}) => {
    const template = selected[key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  };
}
